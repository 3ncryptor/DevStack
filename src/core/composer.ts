import deepmerge from 'deepmerge'

import { buildApprovalsFor, isCatalogName, NODE_CATALOG } from '../catalog/node'
import { TYPE_PAIRS } from '../catalog/pairs'
import { ResolutionError } from '../errors'
import { CLI_PACKAGE } from './manifest'
import {
  dependencyName,
  type DependencyEntry,
  type DevstackModule,
  type ModuleSystem
} from '../types/module'
import { conditionContextFor, evaluateCondition } from './planner/conditions'
import type { DependencyMap, PackageJson } from '../types/package-json'
import { formatDiagnostics, resolveStack } from './resolver/index'

export interface CompositionResult {
  orderedModules: DevstackModule[]
  packageJson: PackageJson
  /** Packages whose install scripts the package manager must be allowed to run (pnpm). */
  buildApprovals: string[]
}

interface DependencyNames {
  dependencies: Map<string, string>
  devDependencies: Map<string, string>
}

/**
 * Collects package names per dependency type, remembering the first module that asked for each.
 * A conditional entry counts only when its condition holds for the whole stack.
 */
function collectDependencyNames(
  modules: readonly DevstackModule[],
  stack: readonly DevstackModule[],
  moduleSystem: ModuleSystem
): DependencyNames {
  const dependencies = new Map<string, string>()
  const devDependencies = new Map<string, string>()
  const context = conditionContextFor(stack, {}, 'wired', moduleSystem)
  const applies = (entry: DependencyEntry): boolean =>
    typeof entry === 'string' || evaluateCondition(entry.when, context)
  for (const moduleDefinition of modules) {
    for (const entry of (moduleDefinition.dependencies ?? []).filter(applies)) {
      const name = dependencyName(entry)
      if (!dependencies.has(name)) dependencies.set(name, moduleDefinition.id)
    }
    for (const entry of (moduleDefinition.devDependencies ?? []).filter(applies)) {
      const name = dependencyName(entry)
      if (!devDependencies.has(name)) devDependencies.set(name, moduleDefinition.id)
    }
  }
  for (const name of dependencies.keys()) {
    devDependencies.delete(name)
  }
  for (const [runtime, types] of TYPE_PAIRS) {
    if (dependencies.has(runtime) && !dependencies.has(types) && !devDependencies.has(types)) {
      devDependencies.set(types, `type pair of ${runtime}`)
    }
  }
  return { dependencies, devDependencies }
}

function toVersionMap(names: Map<string, string>): DependencyMap {
  const entries = [...names.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, owner]): [string, string] => {
      if (!isCatalogName(name)) {
        throw new ResolutionError(`"${name}" (required by ${owner}) is not in the version catalog`)
      }
      return [name, NODE_CATALOG[name].version]
    })
  return Object.fromEntries(entries)
}

export function composeProjectPackageJson(
  projectName: string,
  modules: DevstackModule[],
  /** Every module of the project, for conditional dependencies; a target passes its own subset. */
  stack: readonly DevstackModule[],
  moduleSystem: ModuleSystem
): PackageJson {
  const basePackageJson: PackageJson = {
    name: projectName,
    version: '0.1.0',
    private: true,
    description: `Generated by ${CLI_PACKAGE.name}`,
    scripts: {
      build: 'tsc -p tsconfig.json'
    }
  }

  const withFragments = modules.reduce<PackageJson>(
    (accumulator, moduleDefinition) =>
      deepmerge(accumulator, moduleDefinition.packageJson ?? {}) as PackageJson,
    basePackageJson
  )

  const names = collectDependencyNames(modules, stack, moduleSystem)
  return {
    ...withFragments,
    dependencies: toVersionMap(names.dependencies),
    devDependencies: toVersionMap(names.devDependencies)
  }
}

export function composeModules(
  selectedModuleNames: string[],
  registry: Map<string, DevstackModule>,
  projectName: string,
  moduleSystem: ModuleSystem = 'esm'
): CompositionResult {
  const resolution = resolveStack(selectedModuleNames, registry)
  const errors = resolution.diagnostics.filter((diagnostic) => diagnostic.severity === 'error')
  if (errors.length > 0) {
    throw new ResolutionError(formatDiagnostics(resolution.diagnostics), {
      diagnostics: resolution.diagnostics
    })
  }
  const orderedModules = resolution.modules

  const packageJson = composeProjectPackageJson(
    projectName,
    orderedModules,
    orderedModules,
    moduleSystem
  )
  const installed = [
    ...Object.keys(packageJson.dependencies ?? {}),
    ...Object.keys(packageJson.devDependencies ?? {})
  ]
  return { orderedModules, packageJson, buildApprovals: buildApprovalsFor(installed) }
}
